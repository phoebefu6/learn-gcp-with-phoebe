"""Write assets/gcp-iam-data.js (window.GCP_IAM_DATA) from iam-fixture.json + roles-2026-11-03.json, with json.dumps."""
import json, os
H = os.path.dirname(os.path.abspath(__file__))
d = {"fixture": json.load(open(os.path.join(H, "iam-fixture.json"))), "roles": json.load(open(os.path.join(H, "roles-2026-11-03.json")))}
js = "/* learn-gcp-with-phoebe - IAM bench data (constructed Tidewater fixture + real role permission lists, 2026-11-03). Generated by materials/build-iam-data.py; do not edit. */\nwindow.GCP_IAM_DATA = " + json.dumps(d, separators=(",", ":")) + ";\n"
open(os.path.join(H, "..", "assets", "gcp-iam-data.js"), "w").write(js)
print("bytes", len(js))
