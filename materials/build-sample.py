"""Build assets/gcp-sample.js (the cost bench's data) from the fetched portal files.

Input : the output dir of fetch-taxi-sample.py
Output: assets/gcp-sample.js       window.GCP_SAMPLE, generated with json.dumps
        materials/gcp-sample.json  the same object, read by cost_ref.py
Run   : python build-sample.py <fetch out dir>        (stdlib only)

What is computed here is only a per-column histogram of BigQuery LOGICAL bytes per value, using
BigQuery's documented data type sizes (read at source 2026-11-03,
https://docs.cloud.google.com/bigquery/docs/reference/standard-sql/data-types#data_type_sizes):
INT64 / FLOAT64 / TIMESTAMP 8 logical bytes, STRING 2 + UTF-8 bytes, and "A NULL value for any data
type is calculated as 0 logical bytes". The schema below is the BigQuery public table's column list
(names reported by public analyses of bigquery-public-data.chicago_taxi_trips.taxi_trips; the portal
names differ: trip_id = unique_key, *_centroid_* = pickup_/dropoff_ latitude, longitude, location).
Location strings are rebuilt as WKT "POINT (lon lat)" from the portal's coordinates.
"""
import glob, json, os, sys

SRC = sys.argv[1]
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_sample_schema import SCHEMA  # noqa: E402
FIXED = {"INT64": 8, "FLOAT64": 8, "TIMESTAMP": 8}


def value(r, field):
    v = r.get(field)
    if isinstance(v, dict):  # GeoJSON point -> WKT string, as BigQuery's copy stores it
        lon, lat = v["coordinates"]
        return "POINT (%s %s)" % (repr(float(lon)), repr(float(lat)))
    return v


def size(t, v):
    if v is None:
        return 0
    if t == "STRING":
        return 2 + len(str(v).encode("utf-8"))
    return FIXED[t]


rows = [r for f in sorted(glob.glob(os.path.join(SRC, "slots", "*.json"))) for r in json.load(open(f))]
cols = []
for name, t, field in SCHEMA:
    hist = {}
    for r in rows:
        s = size(t, value(r, field))
        hist[s] = hist.get(s, 0) + 1
    cols.append({"name": name, "type": t, "hist": [[k, hist[k]] for k in sorted(hist)]})

days = []
for f in sorted(glob.glob(os.path.join(SRC, "jan2019_days", "*.json"))):
    d = {}
    for x in json.load(open(f)):
        ca = x.get("pickup_community_area")
        d[None if ca is None else int(ca)] = int(x["n"])
    # NULLs sort first, as in an ascending ORDER BY
    days.append({"day": os.path.basename(f)[:-5],
                 "areas": [[k, d[k]] for k in sorted(d, key=lambda k: (k is not None, k or 0))]})

view = json.load(open(os.path.join(SRC, "view.json")))
full_rows = next(c for c in view["columns"] if c["fieldName"] == "trip_id")["cachedContents"]["non_null"]
ex = []
for r in rows[::4591][:4]:
    ex.append({n: value(r, f) for n, t, f in SCHEMA if n in ("unique_key", "trip_start_timestamp", "trip_miles", "fare", "payment_type", "company", "pickup_community_area")})

out = {
    "source": "City of Chicago, Taxi Trips (2013-2023), dataset wrvz-psew, data.cityofchicago.org; "
              "licence: City of Chicago data portal Terms of Use. BigQuery copy: "
              "bigquery-public-data.chicago_taxi_trips.taxi_trips",
    "retrieved": "2026-11-03",
    "sample_rows": len(rows),
    "sample_method": "132 seeded 15-minute slots, one per month 2013-2023, up to 150 trips each (seed 20261103)",
    "full_rows": int(full_rows),
    "full_rows_note": "row count from the portal's column statistics (trip_id non-null), retrieved 2026-11-03; "
                      "BigQuery's public copy may hold a different count",
    "columns": cols,
    "jan2019": {"rows": sum(n for d in days for _, n in d["areas"]), "days": days},
    "examples": ex,
    "prices": {
        "region": "us-central1 (Iowa), the default table on cloud.google.com/bigquery/pricing",
        "retrieved": "2026-11-03",
        "on_demand_per_tib": 6.25, "free_tib_per_month": 1,
        "min_mb_per_table": 10, "min_mb_per_query": 10,
        "slot_hour": {"Standard": 0.04, "Enterprise": 0.06, "Enterprise 1-year": 0.048, "Enterprise 3-year": 0.036},
    },
}
js = "/* learn-gcp-with-phoebe - cost bench data. Generated by materials/build-sample.py with json.dumps; do not edit. */\n" \
     "window.GCP_SAMPLE = " + json.dumps(out, separators=(",", ":")) + ";\n"
open(os.path.join(REPO, "assets", "gcp-sample.js"), "w").write(js)
json.dump(out, open(os.path.join(REPO, "materials", "gcp-sample.json"), "w"), indent=1)
print("rows", len(rows), "full", full_rows, "jan2019", out["jan2019"]["rows"], "bytes", len(js))
